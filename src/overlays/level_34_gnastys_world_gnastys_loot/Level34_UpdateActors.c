        int i;

        st->knockSpin = 0;
        st->speed = 0x15E;
        st->knockHeading = StepAndLerpAngle8(
            ArcTan2(actor->posX - SPY.posX, actor->posY - SPY.posY, 0),
            g_bSpyroPersistentEulerZ, 0x28, 0x40);
